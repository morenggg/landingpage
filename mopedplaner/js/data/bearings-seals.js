export function getBearingSeal(id) {
  return BEARINGS_SEALS.find((b) => b.id === id) || null;
}

export function bearingsForComponent(componentPath) {
  return BEARINGS_SEALS.filter((b) => (b.componentPaths || []).includes(componentPath));
}
