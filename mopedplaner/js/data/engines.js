export function getEngine(id) {
  return ENGINES.find((e) => e.id === id) || null;
}

export function enginesForModel(modelId) {
  return ENGINES.filter((e) => e.modelIds.includes(modelId));
}

/** Versucht, aus dem Freitext-Motorfeld eines Fahrzeugs einen Motor zu erkennen. */
export function matchEngineFromText(text) {
  if (!text) return null;
  const t = String(text).toLowerCase().replace(/\s+/g, '');
  // Längste IDs zuerst prüfen (m541 vor m54, m53 …)
  const sorted = [...ENGINES].sort((a, b) => b.id.length - a.id.length);
  return sorted.find((e) => t.includes(e.id)) || null;
}
