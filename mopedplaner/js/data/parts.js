export function getPart(id) {
  return PARTS.find((p) => p.id === id) || null;
}

export function partsForComponent(componentPath) {
  return PARTS.filter((p) => p.componentIds.some((c) => c === componentPath));
}

export function partsForModel(modelId) {
  return PARTS.filter((p) => !p.compatibleModelIds.length || p.compatibleModelIds.includes(modelId));
}
